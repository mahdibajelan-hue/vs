#!/usr/bin/env python3
"""Builds the Hamedan compressor-station demo seed.
   python3 supabase/seed/hamedan_cs/build.py            → writes supabase/seed/demo_hamedan_cs.sql (+ parts) and prints the E/P/C figures
Insert-only. The whole seed runs in one transaction with the app's own RPC flags (ex.rpc / mtl.rpc) set locally, the
same way the app's approval RPCs pass the guards; the flags end with the transaction."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from common import *
import m_master, m_eng, m_mat, m_exec

def main():
    parts, stats = [], {}
    for name, mod in [('master', m_master), ('eng', m_eng), ('mat', m_mat), ('exec', m_exec)] + [(n, __import__('m_' + n)) for n in EXTRA if os.path.exists(os.path.join(os.path.dirname(__file__), f'm_{n}.py'))]:
        sql, st = mod.sql()
        parts.append((name, sql)); stats[name] = st
    root = os.path.join(os.path.dirname(__file__), '..')
    head = ["begin;", "select set_config('ex.rpc', '1', true), set_config('mtl.rpc', '1', true), set_config('sch.rpc', '1', true), set_config('rm.rpc', '1', true), set_config('im.rpc', '1', true), set_config('app.cm_rpc', '1', true);"]
    body = [s for _, sql in parts for s in sql]
    with open(os.path.join(root, 'demo_hamedan_cs.sql'), 'w') as f:
        f.write("-- Demo project «ایستگاه تقویت فشار همدان» (all data fictitious). Generated by supabase/seed/hamedan_cs/build.py — do not edit by hand.\n")
        f.write("\n".join(head + body + ["commit;"]) + "\n")
    import json
    print(json.dumps(stats, ensure_ascii=False, indent=1, default=str))

EXTRA = ['cs', 'sched', 'fin', 'gov', 'misc']
if __name__ == '__main__': main()
