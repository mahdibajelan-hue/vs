/** How to use the portfolio module: one section per tab — the question it answers, how to read it, what each figure means. */
export function GuideTab({ onOpenTab }: { onOpenTab: (tab: string) => void }) {
  const [open, setOpen] = useState<string | null>('dashboard')
  return (
    <div className="pf-stack pf-guide">
      <section className="pf-panel">
        <header className="pf-panel-head"><div><h3><BookOpen size={15} /> راهنمای مدیریت سبد پروژه‌ها</h3><p>این ماژول برای تصمیم‌گیری در سطح سبد است و جای کار روزانهٔ پروژه نیست. همهٔ ارقام از ماژول‌هایی خوانده می‌شود که داده را ثبت می‌کنند (چرخهٔ عمر، مالی، اجرا، ریسک و موانع). خالی بودن یک عدد یعنی دادهٔ آن ثبت نشده است و در این حالت مقدار حدسی جایگزین نمی‌شود.</p></div></header>
        <ol className="pf-guide-start">{START.map(([t, d], i) => <li key={t}><span>{fa(i + 1)}</span><div><b>{t}</b><p>{d}</p></div></li>)}</ol>
      </section>

      {SECTIONS.map((s) => (
        <section key={s.tab} className="pf-panel pf-guide-sec">
          <button type="button" className="pf-guide-head" aria-expanded={open === s.tab} onClick={() => setOpen(open === s.tab ? null : s.tab)}>
            {open === s.tab ? <ChevronDown size={15} /> : <ChevronLeft size={15} />}
            <span><b>{s.title}</b><small>{s.question}</small></span>
          </button>
          {open === s.tab && (
            <div className="pf-guide-body">
              <ul>{s.read.map((r, i) => <li key={i}>{r}</li>)}</ul>
              {s.terms && <dl>{s.terms.map(([k, v]) => <div key={k}><dt>{k}</dt><dd>{v}</dd></div>)}</dl>}
              {s.who && <p className="pf-note">دسترسی: {s.who}</p>}
              <button type="button" className="pf-btn" onClick={() => onOpenTab(s.tab)}>رفتن به «{s.title}»</button>
            </div>
          )}
        </section>
      ))}

      <section className="pf-panel">
        <header className="pf-panel-head"><div><h3>سرعت بارگذاری</h3><p>در نخستین ورود، شاخص‌های همهٔ پروژه‌ها از ماژول‌ها خوانده می‌شود. در ورودهای بعدی، آخرین شاخص‌های ذخیره‌شده در همین مرورگر بی‌درنگ نمایش داده می‌شود و به‌روزرسانی در پس‌زمینه انجام می‌شود. برچسب «نمایش دادهٔ … دقیقه پیش» یعنی به‌روزرسانی در جریان است.</p></div></header>
      </section>
    </div>
  )
}
